import { AccountService } from '../accounts/account-service';
import { ContentService } from '../content/content-service';
import { MrpackExporter } from '../content/export/mrpack-exporter';
import { InstalledContentService } from '../content/installed-content-service';
import { ModrinthClient } from '../content/modrinth-client';
import { RendererEvents } from '../core/renderer-events';
import { GameDirectoryMover } from '../instances/game-directory-mover';
import { InstanceCopier } from '../instances/instance-copier';
import { InstanceService } from '../instances/instance-service';
import { JavaService } from '../java/java-service';
import { GameInstaller } from '../minecraft/game-installer';
import { GameSessionService } from '../minecraft/launch/game-session-service';
import { LoaderRegistry } from '../minecraft/loaders/loader-registry';
import { VanillaInstaller } from '../minecraft/vanilla-installer';
import { VersionCatalog } from '../minecraft/version-catalog';
import { VersionManifestService } from '../minecraft/version-manifest';
import { NewsService } from '../news/news-service';
import { ScreenshotService } from '../screenshots/screenshot-service';
import { BackgroundLibrary } from '../settings/background-library';
import { SettingsService } from '../settings/settings-service';
import { SkinService } from '../skins/skin-service';
import { SupportService } from '../support/support-service';
import { TaskManager } from '../tasks/task-manager';
import { PresenceService } from '../discord/presence-service';
import { UpdateService } from '../updates/update-service';
import { WorldService } from '../worlds/world-service';
import { WindowManager } from './window-manager';

export interface LauncherServices {
  events: RendererEvents;
  settings: SettingsService;
  backgrounds: BackgroundLibrary;
  windows: WindowManager;
  tasks: TaskManager;
  versions: VersionCatalog;
  loaders: LoaderRegistry;
  java: JavaService;
  instances: InstanceService;
  gameDirectoryMover: GameDirectoryMover;
  instanceCopier: InstanceCopier;
  mrpackExporter: MrpackExporter;
  worlds: WorldService;
  news: NewsService;
  support: SupportService;
  updates: UpdateService;
  presence: PresenceService;
  accounts: AccountService;
  skins: SkinService;
  installedContent: InstalledContentService;
  content: ContentService;
  sessions: GameSessionService;
  screenshots: ScreenshotService;
}

export async function createServices(): Promise<LauncherServices> {
  const events = new RendererEvents();
  const settings = new SettingsService(events);
  await settings.load();
  const backgrounds = new BackgroundLibrary(settings);
  await backgrounds.createMissingThumbnails();
  const windows = new WindowManager(settings, events);
  const tasks = new TaskManager(events);
  const manifest = new VersionManifestService(() => settings.gamePaths());
  const versions = new VersionCatalog(settings, manifest);
  const loaders = new LoaderRegistry();
  const java = new JavaService();
  const installer = new GameInstaller(settings, new VanillaInstaller(manifest), loaders, java);
  const instances = new InstanceService(settings, events);
  const gameDirectoryMover = new GameDirectoryMover(settings, tasks);
  await gameDirectoryMover.migrateLayout();
  await instances.load();
  const accounts = new AccountService(events, () => windows.current);
  await accounts.load();
  const skins = new SkinService(accounts);
  const modrinth = new ModrinthClient();
  const installedContent = new InstalledContentService(instances, modrinth);
  const content = new ContentService(settings, instances, installedContent, modrinth, tasks);
  const sessions = new GameSessionService(settings, accounts, instances, installer, java, tasks, events, windows);
  const screenshots = new ScreenshotService(settings, instances);
  const instanceCopier = new InstanceCopier(instances, tasks);
  const mrpackExporter = new MrpackExporter(settings, instances, modrinth, tasks);
  const worlds = new WorldService(instances, tasks);
  const support = new SupportService(accounts, settings, instances, sessions);
  const news = new NewsService(support);
  const updates = new UpdateService(tasks, events, sessions, windows);
  const presence = new PresenceService(settings, instances, sessions, windows);
  return { events, settings, backgrounds, windows, tasks, versions, loaders, java, instances, gameDirectoryMover, instanceCopier, mrpackExporter, worlds, news, support, updates, presence, accounts, skins, installedContent, content, sessions, screenshots };
}
